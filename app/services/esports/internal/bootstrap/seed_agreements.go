var seedAgreementVersions = []struct {
	Doc   agreementversion.Doc
	No    string
	Title string
	Body  string
	When  time.Time
}{
	// The published pair: each document's v1.0.0, effective the day the
	// legal files carry. Titles repeat the module's derivation literals
	// because bootstrap never imports a module.
	{agreementversion.Doc("user"), "v1.0.0", "《用户服务协议》", userAgreementBody, time.Date(2026, 8, 19, 0, 0, 0, 0, time.UTC)},
	{agreementversion.Doc("privacy"), "v1.0.0", "《隐私政策》", privacyPolicyBody, time.Date(2026, 8, 19, 0, 0, 0, 0, time.UTC)},
}

func (s *Seed) seedAgreements(ctx context.Context, client *ent.Client) error {
	for _, v := range seedAgreementVersions {
		_, err := client.AgreementVersion.Query().
			Where(agreementversion.DocEQ(v.Doc), agreementversion.NoEQ(v.No)).
			Only(ctx)
		if err == nil {
			continue
		}
		if !ent.IsNotFound(err) {
			return s.plat.HandleEntError(fmt.Errorf("seed: query agreement version %s/%s: %w", v.Doc, v.No, err))
		}
		// Create-when-absent only, never the keep-in-step refresh the
		// test/sku seeds carry: the operator face owns these rows from
		// day one, and a boot must not silently republish a document an
		// operator switched away from.
		if _, err := client.AgreementVersion.Create().
			SetDoc(v.Doc).
			SetNo(v.No).
			SetTitle(v.Title).
			SetBody(v.Body).
			SetEffectiveAt(v.When).
			SetIsCurrent(true).
			Save(ctx); err != nil {
			// Multi-replica boot race: see the game loop's arm — the
			// winning replica created the version too.
			if ent.IsConstraintError(err) {
				if _, reErr := client.AgreementVersion.Query().
					Where(agreementversion.DocEQ(v.Doc), agreementversion.NoEQ(v.No)).
					Only(ctx); reErr == nil {
					continue
				}
			}
			return s.plat.HandleEntError(fmt.Errorf("seed: create agreement version %s/%s: %w", v.Doc, v.No, err))
		}
		s.log.Info("seeded agreement version", "doc", string(v.Doc), "no", v.No)
	}
	return nil
}
