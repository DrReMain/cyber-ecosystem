// Command protoc-gen-go-connect generates Connect server registration code that
// bridges gRPC-style service implementations to a Kratos Connect transport server.
package main

import (
	"fmt"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/types/pluginpb"
)

const generateComment = "// Code generated by protoc-gen-go-connect. DO NOT EDIT."

const connectImport = `connect "cyber-ecosystem/shared-go/kratos/transport/connect"`

func main() {
	protogen.Options{}.Run(func(p *protogen.Plugin) error {
		// Declare proto3 optional support. Connect registration is method-level
		// (Handle* dispatches by the service's Req/Res method value) and is
		// unaffected by field-level optionality, but without this declaration buf
		// warns that the plugin cannot process files using proto3 optional.
		p.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		for _, f := range p.Files {
			if !f.Generate {
				continue
			}
			genFile(p, f)
		}
		return nil
	})
}

func genFile(p *protogen.Plugin, f *protogen.File) {
	if len(f.Services) == 0 {
		return
	}
	g := p.NewGeneratedFile(f.GeneratedFilenamePrefix+"_connect.pb.go", f.GoImportPath)
	g.P(generateComment)
	g.P()
	g.P("package ", f.GoPackageName)
	g.P()
	g.P("import (")
	g.P(connectImport)
	g.P(")")
	for _, svc := range f.Services {
		emitRegister(g, svc)
	}
}

func emitRegister(g *protogen.GeneratedFile, svc *protogen.Service) {
	full := string(svc.Desc.FullName())
	g.P()
	g.P("// Register", svc.GoName, "ConnectServer registers the ", full, " service on a")
	g.P("// Kratos Connect transport server, bridging a gRPC-style implementation.")
	g.P("func Register", svc.GoName, "ConnectServer(srv *connect.Server, svc ", svc.GoName, "Server) {")
	for _, m := range svc.Methods {
		g.P("\t" + methodLine(full, m))
	}
	g.P("}")
}

// methodLine returns the Handle* registration statement for a method.
func methodLine(serviceFullName string, m *protogen.Method) string {
	handle, proc := handleCall(serviceFullName, string(m.Desc.Name()), m.Desc.IsStreamingClient(), m.Desc.IsStreamingServer())
	return fmt.Sprintf("connect.%s(srv, %q, svc.%s)", handle, proc, m.GoName)
}

// handleCall selects the Handle* function name and builds the procedure path from
// the method's streaming flags. Pure function for easy testing.
func handleCall(serviceFullName, methodName string, clientStream, serverStream bool) (handle, procedure string) {
	procedure = "/" + serviceFullName + "/" + methodName
	switch {
	case !clientStream && !serverStream:
		handle = "HandleUnary"
	case !clientStream:
		handle = "HandleServerStream"
	case !serverStream:
		handle = "HandleClientStream"
	default:
		handle = "HandleBidiStream"
	}
	return handle, procedure
}
